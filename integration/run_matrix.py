
# -*- coding: UTF-8 -*-
"""
Run the integration suite against DSpace / DSpace-CRIS stacks in Docker and
build the compatibility matrix.

    python -m integration.run_matrix --list
    python -m integration.run_matrix                              # every target, one after another
    python -m integration.run_matrix -t dspace-9 -t cris-2025.02
    python -m integration.run_matrix -t dspace-10 --keep          # leave the stack running afterwards
    python -m integration.run_matrix --existing --url https://test.example.org/server/api \\
        --name our-test --user admin@example.org                   # an already running installation

Per target: download the upstream docker-compose.yml, add a generated
override (integration/targets.yml explains it), `docker compose up`, wait for
the REST API, create the admin account, run tests/integration with the
report plugin, save the container logs, `docker compose down -v`.

Results: reports/<target>.json (+ .xml JUnit, -docker.log), then
reports/matrix.{md,html,json}. Exit code 1 if any test failed or a stack
could not be started.

--report-only: failed tests only go into the matrix and do not set the exit
code - the matrix documents what each DSpace version supports. The exit code
is still 1 if a stack could not be started, pytest could not run the suite
(exit codes 2-5: interrupted, internal error, usage error, nothing
collected), or - when the matrix is built here - a feature regressed against
--baseline. CI runs every target with --report-only and lets the matrix job
fail only on regressions.

Requirements: Docker with Compose >= 2.24 (for !reset/!override in the
override file), ~4 GB RAM per running target, PyYAML, requests.
"""

import argparse
import json
import os
import re
import shlex
import subprocess
import sys
import time

import requests
import yaml

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TARGETS_FILE = os.path.join(os.path.dirname(os.path.abspath(__file__)), "targets.yml")
REQUIRED_KEYS = ("name", "compose_url", "port")


class StackError(RuntimeError):
    """A target's Docker stack could not be prepared or started."""


# ---------------------------------------------------------------------------
# Targets and compose override
# ---------------------------------------------------------------------------

def load_targets(path=TARGETS_FILE):
    with open(path, encoding="utf-8") as fh:
        data = yaml.safe_load(fh) or {}
    defaults = data.get("defaults") or {}
    targets, names, ports = [], set(), set()
    for index, raw in enumerate(data.get("targets") or []):
        target = {**defaults, **raw, "index": index}
        missing = [k for k in REQUIRED_KEYS if not target.get(k)]
        if missing:
            raise ValueError(f"Target #{index} is missing {missing}")
        if target["name"] in names:
            raise ValueError(f"Duplicate target name {target['name']!r}")
        if target["port"] in ports:
            raise ValueError(f"Duplicate port {target['port']} ({target['name']})")
        names.add(target["name"])
        ports.add(target["port"])
        target.setdefault("label", target["name"])
        target.setdefault("env", {})
        targets.append(target)
    return targets


def project_name(target):
    return "dsit-" + re.sub(r"[^a-z0-9]+", "-", target["name"].lower()).strip("-")


def api_url(target):
    return f"http://localhost:{target['port']}/server/api"


def compose_override(target):
    """Override applied on top of the upstream docker-compose.yml (Compose >= 2.24 merge tags)."""
    port = int(target["port"])
    octet = 10 + int(target["index"])                     # own subnet per target -> parallel-safe
    return f"""# Generated by integration/run_matrix.py for {target['name']} - do not edit
networks:
  dspacenet:
    ipam: !override
      config:
        - subnet: 10.231.{octet}.0/24
services:
  dspace:
    container_name: !reset null
    build: !reset null
    volumes: !override
      - assetstore:/dspace/assetstore
    ports: !override
      - "127.0.0.1:{port}:8080"
    environment:
      dspace__P__server__P__url: "http://localhost:{port}/server"
      dspace__P__ui__P__url: "http://localhost:4000"
      proxies__P__trusted__P__ipranges: "10.231.{octet}"
      dspace__P__name: "Toolkit integration ({target['name']})"
      # large-upload tests: lift Spring's 512MB multipart limit
      SPRING_SERVLET_MULTIPART_MAX_FILE_SIZE: "4GB"
      SPRING_SERVLET_MULTIPART_MAX_REQUEST_SIZE: "4GB"
    depends_on: !override
      dspacedb:
        condition: service_healthy
      dspacesolr:
        condition: service_started
  dspacedb:
    container_name: !reset null
    build: !reset null
    ports: !reset []
    healthcheck:
      test: ["CMD-SHELL", "pg_isready -h localhost -p 5432"]
      interval: 5s
      timeout: 5s
      retries: 120
  dspacesolr:
    container_name: !reset null
    build: !reset null
    ports: !reset []
"""


# ---------------------------------------------------------------------------
# Runner
# ---------------------------------------------------------------------------

class MatrixRunner:
    def __init__(self, workdir=".integration", reports_dir="reports", keep=False, refresh=False,
                 pytest_args=(), run=subprocess.run, http_get=requests.get, sleep=time.sleep,
                 clock=time.monotonic, log=print, report_only=False):
        self.workdir = os.path.abspath(workdir)
        self.reports_dir = os.path.abspath(reports_dir)
        self.keep = keep
        self.refresh = refresh
        self.pytest_args = list(pytest_args)
        self.report_only = report_only
        self.run = run
        self.http_get = http_get
        self.sleep = sleep
        self.clock = clock
        self.log = log

    # -- files --------------------------------------------------------------

    def prepare(self, target):
        directory = os.path.join(self.workdir, target["name"])
        os.makedirs(directory, exist_ok=True)
        upstream = os.path.join(directory, "upstream.yml")
        if self.refresh or not os.path.exists(upstream):
            self.log(f"[{target['name']}] downloading {target['compose_url']}")
            try:
                response = self.http_get(target["compose_url"], timeout=60)
                response.raise_for_status()
            except requests.RequestException as exc:
                raise StackError(f"cannot download compose file: {exc}") from exc
            with open(upstream, "w", encoding="utf-8") as fh:
                fh.write(response.text)
        override = os.path.join(directory, "override.yml")
        with open(override, "w", encoding="utf-8") as fh:
            fh.write(compose_override(target))
        return upstream, override

    def compose(self, target, files, *args, check=True, capture=True):
        command = ["docker", "compose", "-p", project_name(target), "-f", files[0], "-f", files[1], *args]
        env = {**os.environ, **{k: str(v) for k, v in (target.get("env") or {}).items()}}
        result = self.run(command, env=env, capture_output=capture, text=True)
        if check and result.returncode != 0:
            output = ((result.stdout or "") + (result.stderr or "")).strip()[-2000:]
            raise StackError(f"`docker compose {' '.join(args)}` failed ({result.returncode}): {output}")
        return result

    # -- stack lifecycle ---------------------------------------------------

    def backend_state(self, target, files):
        result = self.compose(target, files, "ps", "-a", "--format", "json", "dspace", check=False)
        for line in (result.stdout or "").splitlines():
            line = line.strip()
            if not line:
                continue
            try:
                data = json.loads(line)
            except ValueError:
                continue
            for entry in data if isinstance(data, list) else [data]:
                return (entry.get("State") or "").lower()
        return ""

    def wait_for_api(self, target, files):
        url = api_url(target)
        timeout = float(target.get("startup_timeout", 1200))
        deadline = self.clock() + timeout
        last_error = "no response yet"
        checks = 0
        while self.clock() < deadline:
            try:
                response = self.http_get(url, timeout=10, headers={"Accept": "application/json"})
                if response.status_code == 200 and (response.json() or {}).get("type") == "root":
                    return response.json()
                last_error = f"HTTP {response.status_code}"
            except (requests.RequestException, ValueError) as exc:
                last_error = type(exc).__name__
            checks += 1
            if checks % 6 == 0:                            # ~every 30 s: did the backend die?
                state = self.backend_state(target, files)
                if state in ("exited", "dead"):
                    raise StackError(f"backend container {state} before the API came up")
                self.log(f"[{target['name']}] waiting for {url} ({last_error}, backend {state or '?'})")
            self.sleep(5)
        raise StackError(f"REST API not ready after {timeout:.0f}s ({last_error})")

    def create_admin(self, target, files):
        result = self.compose(
            target, files, "exec", "-T", "dspace", "/dspace/bin/dspace", "create-administrator",
            "-e", target["admin_email"], "-f", "Toolkit", "-l", "Integration",
            "-p", target["admin_password"], "-c", "en", check=False)
        output = (result.stdout or "") + (result.stderr or "")
        if result.returncode != 0 and "already" not in output.lower():
            raise StackError(f"create-administrator failed: {output.strip()[-1000:]}")

    def run_setup(self, target, files):
        """
        Optional per-target DSpace CLI commands (targets.yml "setup"), e.g.
        loading the configurable-entities model. Failures are logged, not
        fatal: tests that need the result report "unsupported" instead.
        """
        for command in target.get("setup") or []:
            args = shlex.split(command)
            result = self.compose(target, files, "exec", "-T", "dspace", "/dspace/bin/dspace", *args, check=False)
            if result.returncode != 0:
                output = ((result.stdout or "") + (result.stderr or "")).strip()[-500:]
                self.log(f"[{target['name']}] setup '{command}' failed (rc {result.returncode}): {output}")
            else:
                self.log(f"[{target['name']}] setup '{command}' done")

    def save_logs(self, target, files):
        result = self.compose(target, files, "logs", "--no-color", "--tail", "3000", check=False)
        path = os.path.join(self.reports_dir, f"{target['name']}-docker.log")
        with open(path, "w", encoding="utf-8") as fh:
            fh.write((result.stdout or "") + (result.stderr or ""))
        return path

    # -- tests ----------------------------------------------------------------

    def pytest_command(self, target):
        name = target["name"]
        return [sys.executable, "-m", "pytest", "tests/integration",
                "-o", "addopts=",                          # no unit-test coverage gate here
                "-p", "integration.report_plugin",
                "--it-report", os.path.join(self.reports_dir, f"{name}.json"),
                "--it-target", name,
                f"--junitxml={os.path.join(self.reports_dir, name + '.xml')}",
                "-q", "-rfEs", *self.pytest_args]

    def run_tests(self, target, url, user, password):
        env = {**os.environ, "DSPACE_IT_URL": url, "DSPACE_IT_USER": user, "DSPACE_IT_PASSWORD": password,
               "DSPACE_IT_TARGET": target["name"], "DSPACE_IT_LABEL": target.get("label", ""),
               "DSPACE_IT_FAMILY": target.get("family", ""),
               "DSPACE_IT_BASE_VERSION": str(target.get("base_version", ""))}
        self.log(f"[{target['name']}] running tests against {url}")
        result = self.run(self.pytest_command(target), env=env, cwd=REPO_ROOT)
        return result.returncode

    def tests_ok(self, code):
        """pytest exit code -> target OK? 1 (some tests failed) is OK with report_only."""
        return code == 0 or (self.report_only and code == 1)

    def write_setup_error(self, target, message):
        path = os.path.join(self.reports_dir, f"{target['name']}.json")
        with open(path, "w", encoding="utf-8") as fh:
            json.dump({"schema": 1, "target": {"name": target["name"], "label": target.get("label", ""),
                                               "api_url": api_url(target), "server": {}},
                       "run": {}, "summary": {}, "results": [], "setup_error": message}, fh, indent=2)

    # -- one target -------------------------------------------------------

    def run_target(self, target):
        """True if the stack came up and every test passed or was skipped (report_only: the suite ran)."""
        os.makedirs(self.reports_dir, exist_ok=True)
        name = target["name"]
        files = None
        try:
            files = self.prepare(target)
            self.log(f"[{name}] starting stack ({project_name(target)})")
            self.compose(target, files, "up", "-d", "--no-build", "--pull", "missing", capture=True)
            info = self.wait_for_api(target, files)
            self.log(f"[{name}] API ready: {info.get('dspaceVersion', '?')}")
            self.create_admin(target, files)
            self.run_setup(target, files)
            code = self.run_tests(target, api_url(target), target["admin_email"], target["admin_password"])
            return self.tests_ok(code)
        except StackError as exc:
            self.log(f"[{name}] STACK ERROR: {exc}")
            self.write_setup_error(target, str(exc))
            return False
        finally:
            if files:
                log_path = self.save_logs(target, files)
                self.log(f"[{name}] container logs: {log_path}")
                if self.keep:
                    self.log(f"[{name}] --keep: stack left running on {api_url(target)}")
                else:
                    self.compose(target, files, "down", "-v", "--remove-orphans", check=False)

    def run_existing(self, name, url, user, password, label=""):
        os.makedirs(self.reports_dir, exist_ok=True)
        target = {"name": name, "label": label or name}
        return self.tests_ok(self.run_tests(target, url, user, password))


# ---------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------

def main(argv=None, runner_factory=MatrixRunner):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("-t", "--target", action="append", default=[], help="Target name (repeatable; default: all)")
    parser.add_argument("--targets-file", default=TARGETS_FILE)
    parser.add_argument("--list", action="store_true", help="List targets and exit")
    parser.add_argument("--keep", action="store_true", help="Leave stacks running after the tests")
    parser.add_argument("--refresh", action="store_true", help="Re-download upstream compose files")
    parser.add_argument("--reports", default="reports", help="Report directory")
    parser.add_argument("--workdir", default=".integration", help="Directory for compose files")
    parser.add_argument("--baseline", help="Previous matrix.json for regression detection")
    parser.add_argument("--no-matrix", action="store_true", help="Don't build the matrix at the end")
    parser.add_argument("--report-only", action="store_true",
                        help="Failed tests only go into the matrix; exit 1 only for stack/pytest errors and "
                             "regressions (used in CI)")
    parser.add_argument("--existing", action="store_true", help="Test an already running installation (no Docker)")
    parser.add_argument("--url", help="--existing: REST API URL, e.g. https://host/server/api")
    parser.add_argument("--name", default="existing", help="--existing: column name in the matrix")
    parser.add_argument("--user", default=os.getenv("DSPACE_IT_USER"), help="--existing: admin email")
    parser.add_argument("--password", default=os.getenv("DSPACE_IT_PASSWORD"),
                        help="--existing: admin password (or DSPACE_IT_PASSWORD)")
    parser.add_argument("pytest_args", nargs="*", help="Extra pytest arguments after --, e.g. -- -k items")
    args = parser.parse_args(argv)

    runner = runner_factory(workdir=args.workdir, reports_dir=args.reports, keep=args.keep,
                            refresh=args.refresh, pytest_args=args.pytest_args, report_only=args.report_only)
    if args.existing:
        if not (args.url and args.user and args.password):
            parser.error("--existing needs --url, --user and --password (or DSPACE_IT_USER/PASSWORD)")
        ok = runner.run_existing(args.name, args.url, args.user, args.password)
        order = [args.name]
    else:
        targets = load_targets(args.targets_file)
        if args.list:
            for t in targets:
                print(f"{t['name']:<16} {t['label']:<40} port {t['port']}  {t['compose_url']}")
            return 0
        unknown = set(args.target) - {t["name"] for t in targets}
        if unknown:
            parser.error(f"unknown target(s): {', '.join(sorted(unknown))}")
        selected = [t for t in targets if not args.target or t["name"] in args.target]
        results = {t["name"]: runner.run_target(t) for t in selected}
        ok = all(results.values())
        order = [t["name"] for t in targets]
        for name, passed in results.items():
            runner.log(f"{'OK  ' if passed else 'FAIL'} {name}")

    if not args.no_matrix:
        from .build_matrix import write_matrix
        matrix = write_matrix(runner.reports_dir, baseline_path=args.baseline, order=order)
        runner.log(f"Matrix written to {os.path.join(runner.reports_dir, 'matrix.md')}")
        if matrix["regressions"]:
            ok = False
    return 0 if ok else 1


if __name__ == "__main__":  # pragma: no cover
    sys.exit(main())
